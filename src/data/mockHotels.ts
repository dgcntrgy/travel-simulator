/** Bir şehir bölgesinin 3 otel seçeneği (`nights: 0`); bilinmeyen bölge → boş dizi */
export function getHotelsForRegion(cityRegion: string): Hotel[] {
  return (SEEDS[cityRegion] ?? []).map((seed) => ({
    ...seed,
    cityRegion,
    nights: 0,
    // Komşu şehirler aynı fotoğrafı göstermesin diye bölge adına göre dönüşümlü
    image: HOTEL_IMAGES[seed.tier][cityRegion.length % 2],
  }));
}
