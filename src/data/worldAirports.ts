/**
 * Dünya havalimanı veri seti (~390 uluslararası / bölgesel IATA havalimanı).
 * Satır: [IATA, şehir (Türkçe), ISO ülke, havalimanı adı, enlem, boylam, şehir merkezi enlem, boylam, kademe, UTC?]
 * - Havalimanı koordinatı uçuş yaylarında, şehir merkezi mekan keşfi / otel önerisinde kullanılır.
 * - Kademe: 1 = küresel hub / başkent, 2 = büyük, 3 = bölgesel (direkt uçuş olasılığını belirler).
 * - UTC yazılmamışsa ülkenin standart (yaz saati hariç) saat farkı geçerlidir.
 */

export interface CountryInfo {
  /** Türkçe ülke adı (mevcut `Airport.country` değerleriyle birebir) */
  name: string;
  utc: number;
  continent: Continent;
  /** Dil kartları için en yakın desteklenen dil */
  language: LanguageCode;
  /** Fiyat seviyesi (1 = Batı Avrupa) */
  costIndex: number;
  carrier?: { airline: string; code: string };
  lowCost?: { airline: string; code: string };
}

type C = [name: string, utc: number, continent: Continent, language: LanguageCode, cost: number, carrier?: string, lowCost?: string];

/** "Türk Hava Yolları|TK" → { airline, code } */
const carrier = (s?: string) => {
  if (!s) return undefined;
  const [airline, code] = s.split("|");
  return { airline, code };
};

