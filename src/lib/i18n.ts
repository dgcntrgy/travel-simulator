export const isLocale = (v: unknown): v is Locale => typeof v === "string" && (LOCALES as readonly string[]).includes(v);

/** Ülke → dil: TR → tr, DE/AT/CH → de, FR/BE → fr, JP → ja, CN/TW → zh, diğer tüm ülkeler → en */
export function localeForCountry(countryCode: string | null | undefined): Locale {
  switch ((countryCode ?? "").toUpperCase()) {
    case "TR":
      return "tr";
    case "DE":
    case "AT":
    case "CH":
      return "de";
    case "FR":
    case "BE":
      return "fr";
    case "JP":
      return "ja";
    case "CN":
    case "TW":
      return "zh";
    default:
      return "en";
  }
}

/** "de-AT,de;q=0.9,en;q=0.8" ya da navigator.languages → desteklenen ilk dil (yoksa null) */
export function localeFromLanguages(tags: readonly string[] | string | null | undefined): Locale | null {
  const list = typeof tags === "string" ? tags.split(",").map((t) => t.split(";")[0]) : (tags ?? []);
  for (const tag of list) {
    const primary = tag.trim().slice(0, 2).toLowerCase();
    if (isLocale(primary)) return primary;
  }
  return null;
}

